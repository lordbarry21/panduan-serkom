'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { getVariant, definitions } = require('../src/variants');
const { planEdit } = require('../src/engine');
const original = require('../data/steps.json');

for (const definition of definitions) {
  test(`${definition.id}: all 55 steps match the bundled document and original workflow`, () => {
    const material = getVariant(definition.id);
    const source = fs.readFileSync(path.join(__dirname, '..', material.source), 'utf8').replace(/^\uFEFF/, '').split(/\r?\n/);
    assert.equal(material.steps.length, 55);
    for (const [index, step] of material.steps.entries()) {
      const [, start, end] = step.source.match(/:(\d+)-(\d+)/);
      assert.equal(step.code, source.slice(+start - 1, +end).map(line => line.startsWith('    ') ? line.slice(4) : line).join('\n'), step.id);
      for (const key of ['id', 'index', 'module', 'step', 'part', 'mode', 'method']) assert.equal(step[key], original[index][key]);
      if (step.mode === 'terminal') assert.equal(step.code.replace(/(?:pesanmakan|laundry|pesantiketfilm|perpustakaan|Food|LaundryItem|Film|Book)(?:Seeder)?/g, 'NAME'), original[index].code.replace(/(?:pesanmakan|Food)(?:Seeder)?/g, 'NAME'));
      for (const note of material.notes[step.id] || []) {
        assert.ok(step.code.includes(note.code), `${step.id}: note fragment`);
        assert.equal(step.code.slice(0, step.code.indexOf(note.code)).split('\n').length, note.line);
      }
    }
    assert.equal(material.bonus.length, 8);
    assert.ok(fs.existsSync(path.join(__dirname, '..', material.bonusSource)));
  });
}

test('renamed model, table, foreign key, view, category and input agree in each variant', () => {
  for (const definition of definitions.slice(1)) {
    const material = getVariant(definition.id);
    const code = material.steps.map(step => step.code).join('\n');
    assert.ok(code.includes(`make:model ${definition.model} -mcr`));
    assert.ok(code.includes(`protected $table = '${definition.plural}';`));
    assert.ok(code.includes(`foreignId('${definition.foreignKey || `${definition.singular}_id`}')`));
    assert.ok(code.includes(`constrained('${definition.plural}')`));
    assert.ok(code.includes(`admin.${definition.plural}.index`));
    assert.ok(code.includes(`required|in:${definition.category.join(',')}`));
    assert.ok(code.includes(`id="${definition.field}" name="${definition.field}"`));
    assert.ok(code.includes(`$${definition.model[0].toLowerCase() + definition.model.slice(1)}->update([`), 'variable matches the controller parameter generated by Artisan');
    assert.ok(!/Food|\bfoods\b|\bfood_id\b|table_number|pesanmakan/.test(code));
    for (const step of material.steps.filter(step => step.mode === 'file')) {
      const classes = text => [...text.matchAll(/class="([^"]*)"/g)].map(match => match[1].replace(`${definition.singular}-card`, 'food-card'));
      assert.deepEqual(classes(step.code), classes(original[step.index].code));
    }
    const step = material.steps.find(step => step.id === 'modul2-4-2-foodcontroller');
    const fixture = `<?php\nclass ${definition.model}Controller {\n    public function index() { return 'old'; }\n    public function create() { return 'keep'; }\n}\n`;
    const result = planEdit(step, fixture);
    assert.ok(result.text.includes(`$${definition.plural} = ${definition.model}::latest()->paginate(10);`));
    assert.ok(result.text.includes("public function create() { return 'keep'; }"));
  }
});
